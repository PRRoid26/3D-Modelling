"""
Borehole Log — Automated Colour & Texture Assignment
=====================================================
SECURITY HARDENING (Rule 4 — COBIT / CERT-In compliance)
---------------------------------------------------------
Every colour or texture assignment is now logged into the PostgreSQL
geo_audit_log table.  The record contains:

    • sap_user   — SAP user token passed from the Flask request context
    • operation  — always 'UPDATE' (we write colour/texture into the workbook)
    • table_name — 'borehole_log'
    • row_ref    — Excel row number (1-based)
    • old_values — JSON snapshot of the cell values before the write
    • new_values — JSON snapshot of the cell values after the write
    • ts         — UTC timestamp (generated by PostgreSQL default)

The application's database user must have INSERT on geo_audit_log but
never UPDATE, DELETE, or TRUNCATE (enforced by the DBA / row-security policy).

Usage (unchanged from before):
    python ruleScript.py <input.xlsx> [output.xlsx]

Dependencies:
    pip install pandas openpyxl psycopg2-binary
"""

import sys
import json
import shutil
import logging
import os
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
from openpyxl import load_workbook
from openpyxl.styles import PatternFill

from dotenv import load_dotenv
load_dotenv()

# ── Audit logger (also captured by the SysLogHandler configured in app.py) ──
audit_log = logging.getLogger("lithosync.audit")

# ── Dev mode flag — set DEV_MODE=true in .env to skip PostgreSQL audit writes ─
DEV_MODE = os.environ.get("DEV_MODE", "").lower() == "true"

# ══════════════════════════════════════════════════════════════════════════════
# RULE 2 (Infrastructure readiness) — DB connection
# psycopg2 is imported lazily so the module still loads even if it is not
# installed (standalone Excel-only usage).  When DATABASE_URL is absent the
# audit function warns and skips the DB write.
# ══════════════════════════════════════════════════════════════════════════════
DATABASE_URL = os.environ.get(
    "DATABASE_URL",
    "postgresql+psycopg2://lithosync:changeme@localhost:5432/lithosync_geo?sslmode=require",
)

# ── Strip the SQLAlchemy dialect prefix so psycopg2 can use the DSN directly ─
def _psycopg2_dsn(url: str) -> str:
    """Convert 'postgresql+psycopg2://...' → 'postgresql://...' for psycopg2."""
    return url.replace("postgresql+psycopg2://", "postgresql://", 1)


# ══════════════════════════════════════════════════════════════════════════════
# RULE 4 — COBIT audit trail: geo_audit_log writer
# ══════════════════════════════════════════════════════════════════════════════
_DDL_CREATE_AUDIT_TABLE = """
CREATE TABLE IF NOT EXISTS geo_audit_log (
    id          BIGSERIAL PRIMARY KEY,
    sap_user    TEXT        NOT NULL,
    operation   TEXT        NOT NULL DEFAULT 'UPDATE',
    table_name  TEXT        NOT NULL DEFAULT 'borehole_log',
    row_ref     TEXT,
    old_values  JSONB,
    new_values  JSONB,
    ts          TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- The application role is NEVER granted UPDATE/DELETE/TRUNCATE on this table.
-- Row-security policy (enabled by the DBA) prevents silent removal even by admins.
"""


def _ensure_audit_table(conn) -> None:
    """Create geo_audit_log if it does not exist (idempotent)."""
    with conn.cursor() as cur:
        cur.execute(_DDL_CREATE_AUDIT_TABLE)
    conn.commit()


def write_audit_record(
    sap_user: str,
    row_ref: str,
    old_values: dict,
    new_values: dict,
    operation: str = "UPDATE",
    table_name: str = "borehole_log",
) -> None:
    """
    Insert one row into geo_audit_log.

    In DEV_MODE (DEV_MODE=true in .env) the PostgreSQL write is skipped
    entirely and a simple info log is emitted instead — no connection
    errors, no spam in the terminal.

    Parameters
    ----------
    sap_user   : SAP user token from the Flask request context.
    row_ref    : Human-readable row identifier (e.g. "Excel row 5").
    old_values : Dict of cell values before the write.
    new_values : Dict of cell values after the write.
    operation  : DML verb — always 'UPDATE' for colour/texture assignments.
    table_name : Source table being audited.
    """

    # ── DEV MODE: skip DB entirely, just print a clean log line ──────────────
    if DEV_MODE:
        audit_log.info(
            f"[DEV MODE] Audit skipped (no PostgreSQL) — "
            f"ROW={row_ref} USER={sap_user} OP={operation}"
        )
        return

    # ── PRODUCTION: write to PostgreSQL geo_audit_log ─────────────────────────
    try:
        import psycopg2  # lazy import
        import psycopg2.extras

        dsn  = _psycopg2_dsn(DATABASE_URL)
        conn = psycopg2.connect(dsn)
        _ensure_audit_table(conn)

        with conn.cursor() as cur:
            cur.execute(
                """
                INSERT INTO geo_audit_log
                    (sap_user, operation, table_name, row_ref, old_values, new_values)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    sap_user,
                    operation,
                    table_name,
                    row_ref,
                    json.dumps(old_values),
                    json.dumps(new_values),
                ),
            )
        conn.commit()
        conn.close()

        audit_log.info(
            f"EVENT=GEO_AUDIT_WRITE USER={sap_user} ROW={row_ref} OP={operation}"
        )

    except ImportError:
        audit_log.warning(
            "psycopg2 not installed — audit record NOT written to PostgreSQL. "
            "Run: pip install psycopg2-binary"
        )
    except Exception as exc:
        # Log the failure but do NOT let a DB outage block the pipeline.
        audit_log.error(
            f"EVENT=GEO_AUDIT_FAILURE USER={sap_user} ROW={row_ref} DETAIL={exc}"
        )


